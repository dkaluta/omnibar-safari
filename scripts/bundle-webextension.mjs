// Rebuild the two local startup files; never fetch code or user data.
import { mkdir, readFile, realpath, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { basename, dirname, relative, resolve, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const resources = resolve(root, 'native/Omnibar/Omnibar Commands/Resources');
const args = process.argv.slice(2);
let check = false, diagnostics = false, installed = null, outdir = null;
const seen = new Set();
for (let index = 0; index < args.length; index++) {
  const option = args[index];
  if (seen.has(option)) throw new Error(`Duplicate option: ${option}`);
  seen.add(option);
  if (option === '--check') check = true;
  else if (option === '--diagnostics') diagnostics = true;
  else if (['--resources', '--outdir'].includes(option) && args[index + 1] && !args[index + 1].startsWith('--')) {
    const path = resolve(args[++index]);
    if (option === '--resources') installed = path;
    else outdir = path;
  } else throw new Error(`Unknown or incomplete option: ${option}`);
}
if ((installed && !check) || (diagnostics && !outdir)) {
  throw new Error('Usage: node scripts/bundle-webextension.mjs [--check [--resources DIRECTORY]] [--outdir DIRECTORY] [--diagnostics (requires --outdir)]');
}
// Resolve symlinked parents too: diagnostics must never replace release files.
async function canonical(path) {
  try { return await realpath(path); }
  catch (error) {
    if (error.code !== 'ENOENT') throw error;
    return resolve(await canonical(dirname(path)), basename(path));
  }
}
if (outdir) {
  const target = await canonical(outdir);
  const release = await realpath(resources);
  const distribution = await canonical(resolve(root, 'build/distribution'));
  const allowed = await Promise.all([resolve(root, 'build/diagnostics'), tmpdir(), '/tmp'].map(canonical));
  if (target === release || target.startsWith(release + sep)
    || target === distribution || target.startsWith(distribution + sep)
    || !allowed.some(directory => target.startsWith(directory + sep))) {
    throw new Error('Explicit output must be an isolated directory under build/diagnostics or a temporary directory, outside release resources and distribution artifacts.');
  }
}
const outputDirectory = outdir ?? resources;
const require = createRequire(resolve(root, 'website/package.json'));
let esbuild;
try { esbuild = require('esbuild'); }
catch { throw new Error('Install the pinned build tools first: npm ci --prefix website'); }
if (esbuild.version !== require('./package.json').devDependencies.esbuild) {
  throw new Error('The installed esbuild differs from the pinned version. Run npm ci --prefix website.');
}

for (const [entry, output] of [['palette-entry.js', 'palette-bundle.js'], ['background-start.js', 'background-bundle.js']]) {
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: [relative(root, resolve(resources, entry))],
    outfile: relative(root, resolve(resources, output)),
    bundle: true, format: 'iife', platform: 'browser', target: ['safari16', 'ios16'],
    define: { __OMNIBAR_STARTUP_DIAGNOSTICS__: String(diagnostics) },
    minify: true, charset: 'utf8', legalComments: 'none', sourcemap: false,
    write: false, metafile: true, logLevel: 'silent',
    banner: { js: `/* Generated by scripts/bundle-webextension.mjs with esbuild ${esbuild.version}. Do not edit. */` },
  });
  if (Object.values(result.metafile.outputs).some(output => output.imports.length)) {
    throw new Error('A startup bundle still loads another JavaScript resource.');
  }
  const generated = result.outputFiles[0].text;
  if (!diagnostics && generated.includes('Omnibar startup timings')) {
    throw new Error('Development diagnostics must not be included in a release bundle.');
  }
  if (check) {
    const locations = [outputDirectory, ...(installed ? [installed] : [])];
    for (const location of locations) {
      let existing;
      try { existing = await readFile(resolve(location, output), 'utf8'); } catch { /* Report below. */ }
      if (existing !== generated) {
        throw new Error(`Missing or stale ${resolve(location, output)}. Regenerate the matching startup bundles, then rebuild the app.`);
      }
    }
  } else {
    await mkdir(outputDirectory, { recursive: true });
    await writeFile(resolve(outputDirectory, output), generated);
  }
}
console.log(check ? 'Verified both startup bundles match the pinned build and current source.'
  : diagnostics ? `Generated development-only timing bundles in ${outputDirectory}.`
    : 'Generated both self-contained WebExtension startup bundles.');
